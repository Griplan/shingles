"""Deterministic local package. data/atlas/... is authoritative; --check never writes."""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
ATLAS=ROOT/'data/atlas/goran-2022-preview-v3'
OUTPUT=ROOT/'miniprogram/data/atlas.generated.ts'
INPUTS=['front.json','back.json','source-map.json','registration.json','sources.json','coverage.json','local-registration.json','hand-registration.json']
def content_hash():
 h=hashlib.sha256()
 for name in INPUTS:h.update(name.encode()+b'\0'+(ATLAS/name).read_bytes()+b'\0')
 return h.hexdigest()
def render():
 manifest=json.loads((ATLAS/'manifest.json').read_text());manifest['contentSHA256']=content_hash()
 regions=[]
 for v in ['front','back']:regions+=json.loads((ATLAS/(v+'.json')).read_text())['regions']
 compact=lambda d:json.dumps(d,ensure_ascii=False,separators=(',',':'))
 return manifest,'// GENERATED by scripts/sync_atlas.py — DO NOT EDIT. Source: data/atlas/goran-2022-preview-v3.\n// Derived atlas data: Goran_tek-en, CC BY-SA 4.0; see source directory NOTICE.md.\nimport { AtlasManifest, AtlasRegion } from "../types/atlas";\nexport const ATLAS_MANIFEST:AtlasManifest='+compact(manifest)+';\nexport const ATLAS_REGIONS:readonly AtlasRegion[]='+compact(regions)+';\n'
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();manifest,text=render()
 actual=json.loads((ATLAS/'manifest.json').read_text())
 if a.check:
  assert actual==manifest,'Canonical manifest hash is stale: run sync_atlas.py'
  assert OUTPUT.exists() and OUTPUT.read_text()==text,'Package copy is stale: run sync_atlas.py'
  print('PASSED: canonical hash and generated package copy agree')
 else:
  (ATLAS/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n');OUTPUT.write_text(text);print('Generated',OUTPUT,'bytes',len(text.encode()))
if __name__=='__main__':main()
