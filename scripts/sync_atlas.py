"""Deterministic local package. data/atlas/... is authoritative; --check never writes."""
import argparse,base64,hashlib,json,struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
ATLAS=ROOT/'data/atlas/goran-2022-preview-v3'
OUTPUT=ROOT/'miniprogram/packages/clinical/data/atlas.generated.ts'
INPUTS=['front.json','back.json','source-map.json','registration.json','sources.json','coverage.json','local-registration.json','hand-registration.json']
def content_hash():
 h=hashlib.sha256()
 for name in INPUTS:h.update(name.encode()+b'\0'+(ATLAS/name).read_bytes()+b'\0')
 return h.hexdigest()
def pack_geometry(geometry):
 if not geometry:return geometry
 polygon_ring_counts=[];ring_point_counts=[];values=[]
 for polygon in geometry['coordinates']:
  polygon_ring_counts.append(len(polygon))
  for ring in polygon:
   ring_point_counts.append(len(ring))
   for x,y in ring:values.extend((float(x),float(y)))
 return {
  'type':'MultiPolygon',
  'polygonRingCounts':polygon_ring_counts,
  'ringPointCounts':ring_point_counts,
  'doublesBase64':base64.b64encode(struct.pack(f'>{len(values)}d',*values)).decode('ascii'),
 }
def pack_region(region):
 compact=dict(region)
 compact['geometry']=pack_geometry(region['geometry'])
 if 'polygonGeometry' in region:compact['polygonGeometry']=pack_geometry(region['polygonGeometry'])
 point=region['labelPoint'];compact['labelPoint']=[point['x'],point['y']]
 return compact
def render():
 manifest=json.loads((ATLAS/'manifest.json').read_text());manifest['contentSHA256']=content_hash()
 regions=[]
 for v in ['front','back']:regions+=json.loads((ATLAS/(v+'.json')).read_text())['regions']
 compact=lambda d:json.dumps(d,ensure_ascii=False,separators=(',',':'))
 packed=[pack_region(region) for region in regions]
 return manifest,'// GENERATED by scripts/sync_atlas.py — DO NOT EDIT. Source: data/atlas/goran-2022-preview-v3.\n// Derived atlas data: Goran_tek-en, CC BY-SA 4.0; see source directory NOTICE.md.\nimport { AtlasManifest } from "../../../types/atlas";\nimport { CompactAtlasRegion, unpackAtlasRegions } from "./atlas-codec";\nexport const ATLAS_MANIFEST:AtlasManifest='+compact(manifest)+';\nconst COMPACT_REGIONS:readonly CompactAtlasRegion[]='+compact(packed)+';\nexport const ATLAS_REGIONS=unpackAtlasRegions(COMPACT_REGIONS);\n'
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();manifest,text=render()
 actual=json.loads((ATLAS/'manifest.json').read_text())
 if a.check:
  assert actual==manifest,'Canonical manifest hash is stale: run sync_atlas.py'
  assert OUTPUT.exists() and OUTPUT.read_text()==text,'Package copy is stale: run sync_atlas.py'
  print('PASSED: canonical hash and generated package copy agree')
 else:
  (ATLAS/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n');OUTPUT.write_text(text);print('Generated',OUTPUT,'bytes',len(text.encode()))
if __name__=='__main__':main()
