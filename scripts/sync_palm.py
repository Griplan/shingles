"""Generate only palm surface/registry. The display source supplies NO dermatomes.
Run --check in validation; original full-body exports are never touched.
"""
import argparse
import hashlib
import json
from pathlib import Path
from shapely.geometry import shape

ROOT = Path(__file__).resolve().parents[1]
RESOURCE = ROOT/'data/body/palm-resource.json'
BODY = ROOT/'data/body/palm-v1.json'
ATLAS = ROOT/'data/atlas/palm-v1'
OUTPUT = ROOT/'miniprogram/data/palm.generated.ts'
VIEWS = {'palm-left': 'left', 'palm-right': 'right'}
INPUTS = ['palm-left.json', 'palm-right.json', 'sources.json', 'registration.json']
BASIS = ['templateId', 'templateVersion', 'geometryId', 'regionSetId']


def serialized(value):
    return json.dumps(value, ensure_ascii=False, indent=2)+'\n'


def render():
    raw = RESOURCE.read_bytes()
    resource = json.loads(raw)
    assert set(resource['views']) == set(VIEWS)
    body = {k: resource[k] for k in BASIS}
    body.update(coordinateSystem='normalized_2d_top_left',
                sourceSHA256={'data/body/palm-resource.json': hashlib.sha256(raw).hexdigest()},
                views={v: {'side': side, 'geometry': resource['views'][v]['body']} for v, side in VIEWS.items()})
    body_text = serialized(body)
    manifest = json.loads((ATLAS/'manifest.json').read_bytes())
    digest = hashlib.sha256()
    for name in INPUTS:
        digest.update(name.encode()+b'\0'+(ATLAS/name).read_bytes()+b'\0')
    manifest['contentSHA256'] = digest.hexdigest()
    assert all(manifest[k] == body[k] for k in BASIS)
    assert manifest['mappingEnabled'] is False and manifest['medicalReviewStatus'] == 'pending'
    identity = dict(template_id=body['templateId'], template_version=body['templateVersion'],
                    geometry_id=body['geometryId'], region_set_id=body['regionSetId'],
                    atlas_id=manifest['atlasId'], atlas_version=manifest['atlasVersion'],
                    atlas_content_sha256=digest.hexdigest(),
                    body_content_sha256=hashlib.sha256(body_text.encode()).hexdigest(),
                    coordinate_system='normalized_2d_top_left')
    models = {}
    for view, side in VIEWS.items():
        source = resource['views'][view]
        geometry = source['body']
        surface = shape(geometry)
        assert surface.is_valid and not surface.is_empty and surface.area > 0
        assert all(0 <= n <= 1 for n in surface.bounds)
        assert source['anatomicalSide'] == side
        for field in ['imagePath', 'svgPath']:
            assert (ROOT/'miniprogram'/source[field].lstrip('/')).is_file()
        polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
        rings = [{'outer': [{'x': x, 'y': y} for x, y in p[0]],
                  'holes': [[{'x': x, 'y': y} for x, y in ring] for ring in p[1:]]} for p in polygons]
        regions = json.loads((ATLAS/(view+'.json')).read_bytes())['regions']
        for region in regions:
            assert region['view'] == view and region['side'] == side
            assert region['partitionType'] == 'spinal_dermatome'
            assert surface.covers(shape(region['geometry']))
        ready = bool(regions) and manifest['technicalValidationStatus'] == 'passed_offline_geometry' and manifest['sourceLicenseStatus'] == 'verified'
        models[view] = dict(id=body['templateId'], version=body['templateVersion'], geometryId=body['geometryId'], regionSetId=body['regionSetId'],
                            name='左手掌' if side == 'left' else '右手掌', view=view,
                            logicalWidth=resource['logicalWidth'], logicalHeight=resource['logicalHeight'],
                            imagePath=source['imagePath'], sourcePath=source['svgPath'], body=rings,
                            resource={**{k: resource['source'][k] for k in ['title','url','author','license']},
                                      'attribution': resource['source']['author']+'；提取掌面外缘与掌纹，截取腕部并镜像另一侧'},
                            atlas=dict(identity=identity, regions=regions, technicalReady=ready,
                                       blockedReason='' if ready else '手掌皮节边界尚未就绪，当前可标注，暂不能计算参考区域。',
                                       **{k: manifest[k] for k in ['sourceTitle','sourceUrl','attribution','medicalReviewStatus','coverageNote']}))
    compact = json.dumps(models, ensure_ascii=False, separators=(',', ':'))
    text = '// GENERATED by scripts/sync_palm.py. Palm source and atlas are independent.\nimport {PalmModel,PalmView} from "../types/palm";\nexport const PALM_MODELS:Readonly<Record<PalmView,PalmModel>>='+compact+';\n'
    return body_text, serialized(manifest), text


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = zip([BODY, ATLAS/'manifest.json', OUTPUT], render())
    for path, text in outputs:
        if args.check:
            assert path.read_text() == text, f'Stale generated palm file: {path.relative_to(ROOT)}'
        else:
            path.write_text(text)
    print('PASSED: palm source geometry, identity, content hashes and package agree' if args.check else 'Generated palm body and client registry; full-body files untouched')

if __name__ == '__main__':
    main()
