"""Deterministically export the existing V2 hitOutline, never redraw it."""
import argparse
import hashlib
import json
from pathlib import Path
from prepare_atlas import ROOT, models

OUTPUT = ROOT/'data/body/commons-template4-hands-v2.json'
PACKAGE = ROOT/'miniprogram/data/matching-body.generated.ts'

def render():
    data = models()
    sources = ['miniprogram/data/body-models.ts', 'miniprogram/assets/body/commons-v1.ts', 'miniprogram/data/body-hands.generated.ts']
    result = {'schemaVersion': 1, 'coordinateSystem': 'normalized_2d_top_left',
              'sourceSHA256': {f: hashlib.sha256((ROOT/f).read_bytes()).hexdigest() for f in sources}, 'views': {}}
    for view, m in data.items():
        points = [[p['x']/m['logicalWidth'], p['y']/m['logicalHeight']] for p in m['hitOutline']]
        if points[-1] != points[0]: points.append(points[0])
        result['views'][view] = {'templateId': m['id'], 'templateVersion': m['version'],
            'geometryId': m['geometryId'], 'regionSetId': m['regionSetId'],
            'geometry': {'type': 'Polygon', 'coordinates': [points]}}
    blob = (json.dumps(result, ensure_ascii=False, indent=2)+'\n').encode()
    digest = hashlib.sha256(blob).hexdigest()
    ts = '// GENERATED by scripts/sync_matching_body.py. No medical boundaries.\nexport const MATCHING_BODY_SHA256="'+digest+'";\n'
    return blob, ts

if __name__ == '__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    blob, ts=render()
    if args.check:
        assert OUTPUT.read_bytes()==blob and PACKAGE.read_text()==ts, 'Shared body is stale; run sync_matching_body.py'
        print('PASSED: shared body equals current V2 hitOutline and package identity')
    else:
        OUTPUT.parent.mkdir(parents=True,exist_ok=True);OUTPUT.write_bytes(blob);PACKAGE.write_text(ts)
        print('Generated shared V2 body and identity')
