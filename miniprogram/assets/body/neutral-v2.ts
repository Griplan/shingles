function reflectReturn(path: readonly PathCommand[]): PathCommand[] {
  const starts: {x:number;y:number}[]=[];
  let p={x:200,y:30};
  for (const c of path) {
    starts.push(p);
    if (c[0]==="M" || c[0]==="L") p={x:c[1],y:c[2]};
    else if (c[0]==="C") p={x:c[5],y:c[6]};
    else if (c[0]==="Q") p={x:c[3],y:c[4]};
  }
  return path.slice(1).map((_,i)=>path.length-1-i).map(i=>{
    const c=path[i], a=starts[i];
    if(c[0]==="C") return ["C",400-c[3],c[4],400-c[1],c[2],400-a.x,a.y];
    if(c[0]==="Q") return ["Q",400-c[1],c[2],400-a.x,a.y];
    return ["L",400-a.x,a.y];
  });
}
