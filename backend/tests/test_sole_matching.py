def test_source_labels_holes_mirror_and_curve_precision():
    _,coarse,_=extract();_,fine,_=extract(.01)
    for side,v in coarse.items():
        assert v['matrix'][0]==v['matrix'][3]==-5.6 # 180 degrees, positive determinant
        for label,g in v['regions'].items():
            assert g.hausdorff_distance(fine[side]['regions'][label])<.001
        assert sum(len(p.interiors) for p in v['regions']['L5'].geoms)==2
    # Actual asymmetric source sides, not a fabricated mirror.
    assert coarse['left']['target'].area!=coarse['right']['target'].area


