    g=box(.30,.32,.70,.50);hole=box(.44,.39,.48,.42)
    q=request(view,[MultiPolygon([g.difference(hole),box(.45,.65,.5,.70)])])
    d=load_dataset(q.identity);expected=q.lesions[0].geometry
