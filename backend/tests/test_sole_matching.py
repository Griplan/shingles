def identity():
    m=json.loads((soles.ATLAS_DIR/'manifest.json').read_text())
    return Identity(template_id=m['templateId'],template_version=m['templateVersion'],geometry_id=m['geometryId'],region_set_id=m['regionSetId'],atlas_id=m['atlasId'],atlas_version=m['atlasVersion'],atlas_content_sha256=m['contentSHA256'],body_content_sha256=hashlib.sha256(soles.BODY_FILE.read_bytes()).hexdigest(),coordinate_system='normalized_2d_top_left')

def request(view='sole-left',geoms=None):
    if geoms is None:geoms=[box(.34,.20,.36,.22)]
    def geom(g):
        parts=[g] if g.geom_type=='Polygon' else list(g.geoms)
        return {'type':'MultiPolygon','coordinateSpace':'body_template_normalized_v1','coordinates':[[[{'x':x,'y':y} for x,y in ring.coords] for ring in [p.exterior,*p.interiors]] for p in parts]}
    return EvaluateRequest(request_id='V64_GEOMETRIC_TEST',annotation_revision=1,identity=identity(),lesions=[{'id':str(i),'view':view,'geometry':geom(g)} for i,g in enumerate(geoms)])

